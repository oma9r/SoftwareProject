package Fitness.InstructorP.Session;

/**
 * The {@code sessionType} enum represents the type of  fitness session, indicating whether the session is
 * conducted online or offline.
 *
 * @author Omar Abumazen
 */
public enum sessionType
{
    /**
     * Indicates that the session is conducted online.
     */
    online,

    /**
     * Indicates that the session is conducted offline.
     */
    offline;
}
